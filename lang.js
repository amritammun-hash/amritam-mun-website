let currentLang = 'en';

function toggleLanguage() {
    currentLang = currentLang === 'en' ? 'hi' : 'en';
    
    // Update button visual
    const langBtn = document.getElementById('lang-toggle-btn');
    if (currentLang === 'hi') {
        langBtn.innerHTML = "अ <span style='opacity:0.5; font-size: 0.8em; margin-left: 5px;'>EN</span>";
        document.body.classList.add('hindi-font');
    } else {
        langBtn.innerHTML = "EN <span style='opacity:0.5; font-size: 0.8em; margin-left: 5px;'>अ</span>";
        document.body.classList.remove('hindi-font');
    }

    // Translate all elements with data-translate-key
    const elements = document.querySelectorAll('[data-translate-key]');
    elements.forEach(el => {
        const key = el.getAttribute('data-translate-key');
        if (dictionary[key] && dictionary[key][currentLang]) {
            el.innerHTML = dictionary[key][currentLang];
        }
    });
}

// Initialize on page load for learn.html
document.addEventListener('DOMContentLoaded', () => {
    const langBtn = document.getElementById('lang-toggle-btn');
    if(langBtn) {
        langBtn.addEventListener('click', toggleLanguage);
    }
});
